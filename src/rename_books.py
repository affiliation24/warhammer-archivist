def main():
    missing, collisions, done = [], [], []
    for old, new in RENAME_MAP.items():
        src = BOOK_DIR / old
        dst = BOOK_DIR / new
        if not src.exists():
            missing.append(old)
            continue
        if dst.exists():
            collisions.append(new)
            continue
        src.rename(dst)
        done.append((old, new))

    print(f"Переименовано: {len(done)}")
    for old, new in done:
        print(f"  {old}  ->  {new}")
    if missing:
        print(f"\nНе найдены на диске ({len(missing)}):")
        for m in missing:
            print(f"  {m}")
    if collisions:
        print(f"\nЦелевое имя уже существует, пропущено ({len(collisions)}):")
        for c in collisions:
            print(f"  {c}")


if __name__ == "__main__":
    main()
