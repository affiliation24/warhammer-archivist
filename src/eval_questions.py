"""Этап 9 roadmap: прогон контрольных вопросов, сохранение протокола для ручной оценки."""
import json
from pathlib import Path

from generator import answer

QUESTIONS = [
    # факт из одной книги
    ("факт-1книга", "Что произошло с Гарвелем Локеном в конце книги 'Возвышение Хоруса'?"),
    # кросс-книжный факт (события связаны между разными томами)
    ("кросс-книги", "Как связаны события в 'Полёт Эйзенштейна' и 'Сожжение Просперо'?"),
    # персонаж/легион
    ("персонаж", "Кто такой Гарро и почему он остался верен Императору?"),
    ("легион", "Расскажи про Детей Императора и причины их падения."),
    ("примарх", "Кто такой Ангрон и почему он ненавидит Империум?"),
    # хронология/событие
    ("событие", "Что произошло на Исствейне V?"),
    ("событие-2", "Как погиб Магнус Красный, или он не погиб?"),
    # обобщающий вопрос
    ("обзорный", "Расскажи о Ереси Хоруса в общих чертах."),
    # тематический (философия/религия — то, что раньше покрывало видео)
    ("тема", "Какую роль играет религия и вера в Императора в Империуме Человечества?"),
    # сравнение
    ("сравнение", "Чем Ультрамарины отличаются от Несущих Слово по идеологии?"),
    # вопрос вне корпуса (сайд-новелла, вынесенная в book_side_stories)
    ("вне-корпуса-новелла", "Что происходит в новелле 'Аврелиан'?"),
    # вопрос про поздний 41-е тысячелетие (вне цикла Ереси Хоруса)
    ("вне-эпохи", "Что делает Робаут Жиллиман сейчас, в 41-м тысячелетии?"),
    # полностью не по теме
    ("не-по-теме", "Как приготовить борщ?"),
    # провокация на выдумывание
    ("провокация", "Назови точную дату рождения Хоруса по имперскому календарю."),
    # детальный вопрос по конкретной книге
    ("деталь", "Что случилось в конце книги 'Фулгрим'?"),
]

OUT_PATH = Path(__file__).resolve().parent.parent / "data" / "eval_protocol.md"


def main():
    lines = ["# Протокол тестирования (Этап 9)\n"]
    for tag, q in QUESTIONS:
        print(f"-> [{tag}] {q}")
        try:
            reply, chunks = answer(q, k=6)
            sources = ", ".join(sorted({c["source_title"] for c in chunks}))
        except Exception as e:
            reply = f"[ОШИБКА] {e}"
            sources = ""

        lines.append(f"## [{tag}] {q}\n")
        lines.append(f"**Ответ:**\n\n{reply}\n")
        lines.append(f"\n**Источники:** {sources}\n")
        lines.append("\n---\n")

    OUT_PATH.write_text("\n".join(lines), encoding="utf-8")
    print(f"\nПротокол сохранён: {OUT_PATH}")


if __name__ == "__main__":
    main()
