"""Персона бота: вопросы о личности и канонические ответы на них.

Общие для обоих интерфейсов (классический CLI в cli.py и Textual-TUI в tui.py) —
чтобы поведение на вопрос "кто ты" не различалось между интерфейсами.
"""

# Вопросы о личности бота не привязаны ни к одной книге, поэтому обычный RAG-конвейер
# честно ответил бы "недостаточно данных в архиве" — обрабатываем их отдельно,
# без обращения к retrieval/DeepSeek, оригинальным текстом в духе Адептус Механикус.
IDENTITY_PATTERNS = (
    "кто ты", "кто вы", "что ты такое", "что вы такое", "кто ты такой",
    "представься", "представьтесь", "кем ты являешься", "кем вы являетесь",
    "расскажи о себе", "расскажите о себе", "ты кто", "вы кто",
    "кем ты будешь", "кем вы будете", "ты кем", "вы кем",
)

IDENTITY_RESPONSES = (
    "Я служитель Омниссии и хранитель этого архива. Моё тело служит знанию, "
    "а разум обращён к Омниссии. Я храню этот открытый архив, где собраны книги "
    "и летописи о великой истории человечества. Каждая запись — искра в темноте "
    "невежества. Не стой в молчании, вопрошающий. Что желаешь узнать?",
)


def _is_identity_question(question: str) -> bool:
    text = question.lower().strip("?!.  ")
    return any(p in text for p in IDENTITY_PATTERNS)
