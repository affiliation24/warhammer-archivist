def strip_markdown(text: str) -> str:
    """Подстраховка на случай, если модель проигнорирует запрет на markdown
    в промпте: убирает звёздочки/решётки и превращает markdown-таблицы в
    обычный текст построчно."""
    import re as _re

    text = _re.sub(r"\*\*(.+?)\*\*", r"\1", text)
    text = _re.sub(r"(?<!\*)\*(?!\*)([^*\n]+?)\*(?!\*)", r"\1", text)
    text = _re.sub(r"^#{1,6}\s*", "", text, flags=_re.MULTILINE)
    lines = []
    for line in text.split("\n"):
        stripped = line.strip()
        if stripped.startswith("|") and stripped.endswith("|"):
            cells = [c.strip() for c in stripped.strip("|").split("|")]
            if all(_re.fullmatch(r"-+", c) for c in cells):
                continue  # разделитель markdown-таблицы вида |---|---|
            lines.append(" — ".join(cells))
        else:
            lines.append(line)
    return "\n".join(lines)


def build_context(chunks: list[dict]) -> str:
    parts = []
    for c in chunks:
        era = c.get("era") or classify_chunk_era(c)
        era_label = ERA_LABELS.get(era, "эпоха не определена явно")
        parts.append(f"[Источник: {c['source_title']}, эпоха: {era_label}]\n{c['text']}")
    return "\n\n---\n\n".join(parts)


@retry(
    retry=retry_if_exception_type(
        (APIConnectionError, APITimeoutError, InternalServerError, PermissionDeniedError)
    ),
    stop=stop_after_attempt(4),
    wait=wait_exponential(multiplier=1, min=2, max=30),
    reraise=True,
)
def _call_groq(client: Groq, messages: list[dict]) -> str:
    try:
        resp = client.chat.completions.create(
            model=GROQ_MODEL,
            messages=messages,
            temperature=0.2,
            max_tokens=2048,
        )
    except RateLimitError as e:
        # лимит исчерпан (429) — повторять запрос немедленно бессмысленно,
        # поэтому конвертируем сразу, в обход retry= (см. декоратор выше)
        raise TokensExhaustedError(random.choice(TECHPRIEST_QUOTA_MESSAGES)) from e
    # PermissionDeniedError (403) НЕ ловим здесь — даём ему долететь наружу
    # нетронутым, чтобы retry= (см. декоратор) успел его повторить; в понятное
    # сообщение оборачиваем только после исчерпания попыток, в answer() ниже
    return resp.choices[0].message.content


def answer(
    question: str, k: int = 6, era_chunks_override: list[dict] | None = None
) -> tuple[str, list[dict]]:
    api_key = os.environ.get("GROQ_API_KEY")
    if not api_key:
        raise RuntimeError(
            "GROQ_API_KEY не найден. Создай .env в корне проекта со строкой "
            "GROQ_API_KEY=твой_ключ (получить на https://console.groq.com/keys)"
        )
    client = Groq(api_key=api_key)

    if era_chunks_override is not None:
        # пользователь уже выбрал эпоху после уточняющего вопроса — используем
        # заранее подготовленный набор чанков этой эпохи, повторный поиск не нужен
        chunks = era_chunks_override
    else:
        # исправляем опечатки перед поиском — дальше question уже "чистый" везде:
        # и для retrieval, и для итогового вопроса модели (см. correct_typos выше)
        question = correct_typos(question)
        # берём пул шире k — как для надёжного обнаружения смешения эпох, так и как
        # "площадку" для адаптивной глубины: k здесь не жёсткий потолок, а ориентир
        # размера пула, из которого adaptive_k сам решает, сколько чанков реально
        # использовать, по тому, как быстро падает релевантность (см. retriever.py)
        pool = retrieve(question, k=max(k * 4, 20))
        for c in pool:
            c["era"] = classify_chunk_era(c)
        eras_present = {c["era"] for c in pool if c["era"] != ERA_UNKNOWN}
        if len(eras_present) > 1:
            by_era = {}
            for era in eras_present:
                bucket = [c for c in pool if c["era"] == era]
                n = adaptive_k([c["score"] for c in bucket], k_min=3, k_max=MAX_CONTEXT_CHUNKS)
                by_era[era] = bucket[:n]
            raise EraClarificationNeeded(question=question, by_era=by_era)
        n = adaptive_k([c["score"] for c in pool], k_min=3, k_max=MAX_CONTEXT_CHUNKS)
        chunks = pool[:n]

    context = build_context(chunks)

    messages = [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": f"Контекст:\n\n{context}\n\nВопрос: {question}"},
    ]

    try:
        reply = _call_groq(client, messages)
    except PermissionDeniedError as e:
        # retry= в _call_groq уже исчерпал попытки на этом моменте —
        # значит отказ стабильный, сообщаем пользователю понятно
        raise AccessDeniedError(TECHPRIEST_ACCESS_DENIED_MESSAGE) from e
    return strip_markdown(reply), chunks


if __name__ == "__main__":
    import sys
    q = " ".join(sys.argv[1:]) or "Кто такой Хорус и почему он предал Императора?"
    reply, chunks = answer(q)
    print(reply)
    print("\nИсточники:", ", ".join(sorted({c["source_title"] for c in chunks})))
