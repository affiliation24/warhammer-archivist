ERA_HERESY = "heresy"
ERA_CURRENT = "current"
ERA_UNKNOWN = "unknown"

ERA_LABELS = {
    ERA_HERESY: "Ересь Хоруса / Великий Крестовый поход, ~M30-31",
    ERA_CURRENT: "современный Империум, ~M41-42",
}

# ключевые слова для грубой эвристической классификации эпохи вики-статей —
# книги (cycle=horus_heresy/primarchs) всегда однозначно M30-31, а вот вики-статья
# про персонажа может описывать его и во время Ереси, и в текущем 41-м тысячелетии
_HERESY_MARKERS = (
    "ересь хоруса", "крестовый поход", "m30", "m31", "м30", "м31",
    "30-е тысячелетие", "31-е тысячелетие", "30-го тысячелетия", "31-го тысячелетия",
)
_CURRENT_MARKERS = (
    "m41", "m42", "м41", "м42", "41-е тысячелетие", "42-е тысячелетие",
    "41-го тысячелетия", "42-го тысячелетия", "индомитус", "в настоящее время",
    "в наши дни", "ныне", "на сегодняшний день",
)


def classify_chunk_era(chunk: dict) -> str:
    """Эвристическая метка эпохи чанка. Для книг обоих текущих циклов эпоха известна
    точно (обе — Крестовый поход/Ересь). Для вики — по ключевым словам в заголовке
    и начале текста; если маркеров нет или есть маркеры обеих эпох — "unknown"
    (модель тогда сама прямо скажет, что эпоха не определена, вместо угадывания)."""
    if chunk.get("cycle") in ("horus_heresy", "primarchs", "siege_of_terra", "night_lords"):
        return ERA_HERESY
    haystack = f"{chunk.get('chapter_title') or ''} {chunk['text'][:400]}".lower()
    has_heresy = any(m in haystack for m in _HERESY_MARKERS)
    has_current = any(m in haystack for m in _CURRENT_MARKERS)
    if has_heresy and not has_current:
        return ERA_HERESY
    if has_current and not has_heresy:
        return ERA_CURRENT
    return ERA_UNKNOWN


class EraClarificationNeeded(RuntimeError):
    """Retrieval нашёл релевантные чанки из разных, взаимоисключающих эпох —
    прежде чем отвечать, нужно уточнить у пользователя, какая эпоха имелась в виду."""

    def __init__(self, question: str, by_era: dict[str, list[dict]]):
        self.question = question
        self.by_era = by_era
        super().__init__("Требуется уточнение эпохи")


